CREATE TABLE MEDICATION_DISPENSE (
    dispense_id INT AUTO_INCREMENT,
    prescription_id INT NULL,
    loc_id INT NULL,
    product_id INT NULL,
    dosage_id INT NULL,
    patient_id INT NOT NULL,
    rp_id INT NULL,
    hp_id INT NULL,
    status VARCHAR(50) NULL,
    quantity_value DECIMAL(10,2) NULL,
    quantity_unit VARCHAR(50) NULL,
    dispense_date DATETIME NULL,
    is_substituted BOOLEAN NULL,
    substitution_reason VARCHAR(255) NULL,
    batch_lot_number VARCHAR(100) NULL,
    expiration_date DATE NULL,
    CONSTRAINT PK_MEDICATION_DISPENSE PRIMARY KEY (dispense_id),
    CONSTRAINT FK_DISP_PRESCRIPTION FOREIGN KEY (prescription_id) REFERENCES MEDICATION_PRESCRIPTION(prescription_id) ON DELETE SET NULL,
    CONSTRAINT FK_DISP_LOCATION FOREIGN KEY (loc_id) REFERENCES LOCATION(loc_id) ON DELETE SET NULL,
    CONSTRAINT FK_DISP_PRODUCT FOREIGN KEY (product_id) REFERENCES PRODUCT_CATALOG(product_id) ON DELETE SET NULL,
    CONSTRAINT FK_DISP_DOSAGE FOREIGN KEY (dosage_id) REFERENCES DOSAGE_DETAILS(dosage_id) ON DELETE SET NULL,
    CONSTRAINT FK_DISP_PATIENT FOREIGN KEY (patient_id) REFERENCES PATIENT(patient_id) ON DELETE CASCADE,
    CONSTRAINT FK_DISP_RP FOREIGN KEY (rp_id) REFERENCES RELATED_PERSON(rp_id) ON DELETE SET NULL,
    CONSTRAINT FK_DISP_HP FOREIGN KEY (hp_id) REFERENCES HEALTH_PROFESSIONAL(hp_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;