CREATE TABLE MEDICATION_ADMINISTRATION (
    admin_id INT AUTO_INCREMENT,
    patient_id INT NOT NULL,
    hp_id INT NULL,
    product_id INT NULL,
    condition_id INT NULL,
    obs_id INT NULL,
    status VARCHAR(50) NULL,
    occurrence_date DATETIME NULL,
    occurrence_start DATETIME NULL,
    occurrence_end DATETIME NULL,
    dosage_id INT NULL,
    admin_note TEXT NULL,
    CONSTRAINT PK_MEDICATION_ADMINISTRATION PRIMARY KEY (admin_id),
    CONSTRAINT FK_ADMIN_PATIENT FOREIGN KEY (patient_id) REFERENCES PATIENT(patient_id) ON DELETE CASCADE,
    CONSTRAINT FK_ADMIN_HP FOREIGN KEY (hp_id) REFERENCES HEALTH_PROFESSIONAL(hp_id) ON DELETE SET NULL,
    CONSTRAINT FK_ADMIN_PRODUCT FOREIGN KEY (product_id) REFERENCES PRODUCT_CATALOG(product_id) ON DELETE SET NULL,
    CONSTRAINT FK_ADMIN_CONDITION FOREIGN KEY (condition_id) REFERENCES HEALTH_CONDITIONS(condition_id) ON DELETE SET NULL,
    CONSTRAINT FK_ADMIN_OBS FOREIGN KEY (obs_id) REFERENCES OBSERVATION_RESULTS(obs_result_id) ON DELETE SET NULL,
    CONSTRAINT FK_ADMIN_DOSAGE FOREIGN KEY (dosage_id) REFERENCES DOSAGE_DETAILS(dosage_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;