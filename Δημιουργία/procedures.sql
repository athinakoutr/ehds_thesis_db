CREATE TABLE PROCEDURES (
    procedure_id INT AUTO_INCREMENT,
    code VARCHAR(100) NULL,
    occurrence_start DATETIME NULL,
    occurrence_end DATETIME NULL,
    hp_id INT NULL,
    statement_id INT NOT NULL,
    body_site_id INT NULL,
    outcome VARCHAR(255) NULL,
    complication TEXT NULL,
    condition_id INT NULL,
    obs_id INT NULL,
    reason_procedure_id INT NULL,
    device_id INT NULL,
    status VARCHAR(50) NULL,
    CONSTRAINT PK_PROCEDURES PRIMARY KEY (procedure_id),
    CONSTRAINT FK_PROC_STATEMENT FOREIGN KEY (statement_id) REFERENCES CLINICAL_STATEMENT(statement_id) ON DELETE CASCADE,
    CONSTRAINT FK_PROC_HP FOREIGN KEY (hp_id) REFERENCES HEALTH_PROFESSIONAL(hp_id) ON DELETE SET NULL,
    CONSTRAINT FK_PROC_BODY_SITE FOREIGN KEY (body_site_id) REFERENCES BODY_STRUCTURE(body_site_id) ON DELETE SET NULL,
    CONSTRAINT FK_PROC_CONDITION FOREIGN KEY (condition_id) REFERENCES HEALTH_CONDITIONS(condition_id) ON DELETE SET NULL,
    CONSTRAINT FK_PROC_OBS FOREIGN KEY (obs_id) REFERENCES OBSERVATION_RESULTS(obs_result_id) ON DELETE SET NULL,
    CONSTRAINT FK_PROC_REASON_PROC FOREIGN KEY (reason_procedure_id) REFERENCES PROCEDURES(procedure_id) ON DELETE SET NULL,
    CONSTRAINT FK_PROC_DEVICE FOREIGN KEY (device_id) REFERENCES MEDICAL_DEVICES_AND_IMPLANTS(device_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;